pub const RETRIEVE_ACTIVE_SESSION_REVIEW_QUESTIONS: &str = "
WITH DECK_IDS AS (
    SELECT
        DECK_ID
    FROM SESSION_DECK WHERE SESSION_ID = ?
),
QUESTIONS AS (
    SELECT
        Q.ID,
        Q.DECK_ID,
        Q.CORRECT,
        Q.INCORRECT,
        Q.REVIEWED
FROM QUESTION Q
WHERE Q.DECK_ID IN (SELECT DECK_ID FROM DECK_IDS)
)
SELECT
  SRQ.ID,
  SRQ.SESSION_REVIEW_ID,
  SRQ.QUESTION_ID,
  SRQ.PRIORITY_INDEX,
  SRQ.INCORRECT_COUNT,
  SRQ.REVIEW_COUNT,
  SRQ.ACTIVE,
  SRQ.CREATED::VARCHAR,
  SRQ.UPDATED::VARCHAR
FROM QUESTIONS AS Q
LEFT JOIN DECK_IDS AS DIDS
ON Q.DECK_ID = DIDS.DECK_ID
LEFT JOIN SESSION_REVIEW_QUESTION AS SRQ
ON Q.ID = SRQ.QUESTION_ID
WHERE SRQ.ACTIVE = TRUE
ORDER BY SRQ.INCORRECT_COUNT, SRQ.REVIEW_COUNT ASC";

