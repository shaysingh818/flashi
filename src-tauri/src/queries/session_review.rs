pub const GENERATE_SESSION_REVIEW_QUESTIONS: &str = "
WITH DECK_IDS AS (
    SELECT
        DECK_ID
    FROM SESSION_DECK WHERE SESSION_ID = ?
),
QUESTIONS AS (
    SELECT
        Q.ID,
        Q.DECK_ID,
        Q.CORRECT,
        Q.INCORRECT,
        Q.REVIEWED
FROM QUESTION Q
WHERE Q.DECK_ID IN (SELECT DECK_ID FROM DECK_IDS)
)
SELECT
    Q.ID
FROM QUESTIONS AS Q
LEFT JOIN DECK_IDS AS DIDS
ON Q.DECK_ID = DIDS.DECK_ID
ORDER BY Q.CORRECT DESC";




