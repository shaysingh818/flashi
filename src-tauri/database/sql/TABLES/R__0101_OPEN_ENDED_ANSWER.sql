CREATE SEQUENCE IF NOT EXISTS OPEN_ENDED_ANSWER_ID_SEQ;

CREATE TABLE IF NOT EXISTS OPEN_ENDED_ANSWER (
    ANSWER_ID     INTEGER     PRIMARY KEY DEFAULT NEXTVAL('OPEN_ENDED_ANSWER_ID_SEQ'),
    KEYWORDS      VARCHAR[],
    ANSWER        TEXT,
    EXPLANATION   TEXT,
    CREATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);