CREATE SEQUENCE SESSION_ID_SEQ START 1;
CREATE SEQUENCE SESSION_DECK_ID_SEQ START 1;
CREATE SEQUENCE SESSION_METRICS_ID_SEQ START 1;

CREATE TABLE SESSION (
    ID            INTEGER     PRIMARY KEY DEFAULT nextval('SESSION_ID_SEQ'),
    NAME          VARCHAR     NOT NULL,
    START_TIME    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    END_TIME      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE SESSION_DECK (
    ID          INTEGER     PRIMARY KEY DEFAULT nextval('SESSION_DECK_ID_SEQ'),
    SESSION_ID  INTEGER     NOT NULL REFERENCES SESSION(ID),
    DECK_ID     INTEGER     NOT NULL,
    CREATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE SESSION_METRICS (
    ID                          INTEGER     PRIMARY KEY DEFAULT nextval('SESSION_METRICS_ID_SEQ'),
    SESSION_ID                  INTEGER     NOT NULL REFERENCES SESSION(ID),
    QUESTIONS_REVIEWED          INTEGER     NOT NULL,
    QUESTIONS_CORRECT           INTEGER     NOT NULL,
    QUESTION_INCORRECT          INTEGER     NOT NULL, 
    QUESTION_COMPLETION_TIME    FLOAT       NOT NULL,
    DECKS_REVIEWED              INTEGER     NOT NULL,
    UPDATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
