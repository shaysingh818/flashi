CREATE SEQUENCE IF NOT EXISTS MULTIPLE_CHOICE_ID_SEQ;
CREATE SEQUENCE IF NOT EXISTS MULTIPLE_CHOICE_ANSWER_ID_SEQ;

CREATE TABLE IF NOT EXISTS MULTIPLE_CHOICE (
    ANSWER_ID        INTEGER        PRIMARY KEY DEFAULT NEXTVAL('MULTIPLE_CHOICE_ID_SEQ'),
    CREATED          TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED          TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS MULTIPLE_CHOICE_ANSWER (
    ID            INTEGER     PRIMARY KEY DEFAULT NEXTVAL('MULTIPLE_CHOICE_ANSWER_ID_SEQ'),
    ANSWER_ID     INTEGER     NOT NULL REFERENCES MULTIPLE_CHOICE(ANSWER_ID),
    IS_CORRECT    BOOLEAN     NOT NULL,
    ANSWER        TEXT,
    EXPLANATION   TEXT,
    CREATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);


