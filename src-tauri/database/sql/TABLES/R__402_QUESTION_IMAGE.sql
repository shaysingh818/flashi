CREATE SEQUENCE IF NOT EXISTS QUESTION_IMAGE_ID_SEQ;

CREATE TABLE IF NOT EXISTS QUESTION_IMAGE (
    ID              INTEGER     PRIMARY KEY DEFAULT NEXTVAL('QUESTION_IMAGE_ID_SEQ'),
    QUESTION_ID     INTEGER     NOT NULL REFERENCES QUESTION(ID),
    IMAGE_ID        INTEGER     NOT NULL REFERENCES IMAGE_ARTIFACT(ID), 
    CREATED         TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED         TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(QUESTION_ID, IMAGE_ID)
);