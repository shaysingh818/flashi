CREATE SEQUENCE IF NOT EXISTS SESSION_REVIEW_METRICS_ID_SEQ;

CREATE TABLE IF NOT EXISTS SESSION_REVIEW_METRICS (
    ID                          INTEGER     PRIMARY KEY DEFAULT NEXTVAL('SESSION_REVIEW_METRICS_ID_SEQ'),
    SESSION_REVIEW_ID           INTEGER     NOT NULL REFERENCES SESSION_REVIEW(ID),
    QUESTIONS_CORRECT           INTEGER     DEFAULT 0,
    QUESTION_INCORRECT          INTEGER     DEFAULT 0, 
    ACCURACY                    FLOAT       NOT NULL,
    TOTAL_REVIEW_COUNT          INTEGER     DEFAULT 0,     
    NUMBER_OF_CYCLES            INTEGER     DEFAULT 0, 
    REVIEW_TIME                 FLOAT       NOT NULL,
    CREATED                     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
