-- Open ended answers
WITH OPEN_ENDED_IMPORTS AS (
	SELECT DISTINCT
		QUESTION_ID,
		QUESTION_ANSWER_ID,
		OPEN_ENDED_ANSWER_ID,
		OPEN_ENDED_ANSWER,
		OPEN_ENDED_ANSWER_KEYWORDS,
