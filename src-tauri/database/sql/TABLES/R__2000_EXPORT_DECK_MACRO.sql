CREATE OR REPLACE MACRO EXPORT_DECK(P_DECK_ID) AS TABLE 
SELECT 
	D.ID AS DECK_ID,
	D.NAME AS DECK_NAME,
	D.TAGS AS DECK_TAGS, 
	D.DESCRIPTION AS DECK_DESCRIPTION,
	Q.ID AS QUESTION_ID,
	Q.RAW AS QUESTION_RAW_TEXT,
	Q.ANSWER_ID AS QUESTION_ANSWER_ID,
	IA.IMAGE_PATH AS QUESTION_IMAGE_ARTIFACT, 
	Q.REVIEWED AS QUESTION_REVIEW_COUNT,
	Q.CORRECT AS QUESTION_CORRECT,
	Q.INCORRECT AS QUESTION_INCORRECT,
	ANS_TYPE.ID AS ANSWER_TYPE_ID,
	ANS_TYPE.NAME AS ANSWER_TYPE_NAME,
	OPN_ENDED.ANSWER_ID AS OPEN_ENDED_ANSWER_ID,
	OPN_ENDED.ANSWER AS OPEN_ENDED_ANSWER,
	OPN_ENDED.KEYWORDS AS OPEN_ENDED_ANSWER_KEYWORDS,
	OPN_ENDED.EXPLANATION AS OPEN_ENDED_EXPLANATION,
	MCHOICE.ANSWER_ID AS MULTIPLE_CHOICE_ANSWER_ID,
	MCHOICE.IS_CORRECT AS MULTIPLE_CHOICE_IS_CORRECT,
	MCHOICE.ANSWER AS MULTIPLE_CHOICE_ANSWER,
	MCHOICE.EXPLANATION AS MULTIPLE_CHOICE_EXPLANATION,
	SEQ.ANSWER_ID AS ORDERED_SEQUENCE_ANSWER_ID,
	SEQ.SEQUENCE AS ORDERED_SEQUENCE_VALUE,
	SEQ.EXPLANATION AS ORDERED_SEQUENCE_EXPLANATION
FROM QUESTION AS Q 
LEFT JOIN DECK AS D
	ON D.ID = Q.DECK_ID
LEFT JOIN ANSWER_TYPE AS ANS_TYPE
	ON ANS_TYPE.ID = Q.ANSWER_TYPE_ID
LEFT JOIN OPEN_ENDED_ANSWER AS OPN_ENDED
	ON OPN_ENDED.ANSWER_ID = Q.ANSWER_ID 
	AND Q.ANSWER_TYPE_ID = 1
LEFT JOIN MULTIPLE_CHOICE_ANSWER AS MCHOICE
	ON MCHOICE.ANSWER_ID = Q.ANSWER_ID 
	AND Q.ANSWER_TYPE_ID = 2
LEFT JOIN ORDERED_SEQUENCE_ANSWER AS SEQ
	ON SEQ.ANSWER_ID = Q.ANSWER_ID 
	AND Q.ANSWER_TYPE_ID = 3
LEFT JOIN QUESTION_IMAGE AS QI
	ON QI.QUESTION_ID = Q.ID
LEFT JOIN IMAGE_ARTIFACT AS IA
	ON IA.ID = QI.IMAGE_ID
WHERE Q.DECK_ID = P_DECK_ID
ORDER BY Q.ID;

