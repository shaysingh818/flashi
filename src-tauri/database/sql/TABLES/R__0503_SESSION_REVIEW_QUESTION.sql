CREATE SEQUENCE IF NOT EXISTS SESSION_REVIEW_QUESTION_ID_SEQ;

CREATE TABLE IF NOT EXISTS SESSION_REVIEW_QUESTION (
    ID                          INTEGER     PRIMARY KEY DEFAULT NEXTVAL('SESSION_REVIEW_QUESTION_ID_SEQ'),
    SESSION_REVIEW_ID           INTEGER     NOT NULL REFERENCES SESSION_REVIEW(ID),
    QUESTION_ID                 INTEGER     NOT NULL REFERENCES QUESTION(ID),
    PRIORITY_INDEX              INTEGER     DEFAULT 0,
    INCORRECT_COUNT             INTEGER     DEFAULT 0, 
    REVIEW_COUNT                INTEGER     DEFAULT 0, 
    ACTIVE                      BOOLEAN     NOT NULL,
    UPDATED                     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED                     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
