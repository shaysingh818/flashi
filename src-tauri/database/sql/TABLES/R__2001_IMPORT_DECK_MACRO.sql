-- Import deck
CREATE OR REPLACE TABLE DECK_IMPORT AS
SELECT
	nextval('DECK_ID_SEQ') AS ID,
	SUBJECT_ID,
	NAME,
	TAGS,
	DESCRIPTION
FROM  (
	SELECT DISTINCT
		1 AS SUBJECT_ID,
		DECK_NAME AS NAME,
		DECK_TAGS AS TAGS,
		DECK_DESCRIPTION AS DESCRIPTION
	FROM '/home/shay-gaming/Desktop/deck.csv'
) dedup;
	
-- Open ended answers
CREATE OR REPLACE TABLE OPEN_ENDED_IMPORT AS
SELECT
    nextval('OPEN_ENDED_ANSWER_ID_SEQ') AS ANSWER_ID,
    DECK_NAME AS SRC_DECK_NAME,
    QUESTION_ID AS SRC_QUESTION_ID,
    OPEN_ENDED_ANSWER_KEYWORDS AS KEYWORDS,
    OPEN_ENDED_ANSWER AS ANSWER,
    OPEN_ENDED_EXPLANATION AS EXPLANATION
FROM (
    SELECT DISTINCT
        DECK_NAME, QUESTION_ID, OPEN_ENDED_ANSWER_KEYWORDS, OPEN_ENDED_ANSWER, OPEN_ENDED_EXPLANATION
    FROM '/home/shay-gaming/Desktop/deck.csv'
    WHERE ANSWER_TYPE_ID = 1
) dedup;


CREATE OR REPLACE TABLE ORDERED_SEQUENCE_IMPORT AS
SELECT
    nextval('ORDERED_SEQUENCE_ANSWER_ID_SEQ') AS ANSWER_ID,
    DECK_NAME AS SRC_DECK_NAME,
    QUESTION_ID AS SRC_QUESTION_ID,
    ORDERED_SEQUENCE_VALUE AS SEQUENCE,
    ORDERED_SEQUENCE_EXPLANATION AS EXPLANATION
FROM (
    SELECT DISTINCT
        DECK_NAME, QUESTION_ID, ORDERED_SEQUENCE_VALUE, ORDERED_SEQUENCE_EXPLANATION
    FROM '/home/shay-gaming/Desktop/deck.csv'
    WHERE ANSWER_TYPE_ID = 3
) dedup;

CREATE OR REPLACE TABLE QUESTION_IMPORT AS
SELECT
    nextval('QUESTION_ID_SEQ') AS ID,
    D.ID AS DECK_ID,
    Q.ANSWER_TYPE_ID,
    COALESCE(OE.ANSWER_ID, OS.ANSWER_ID) AS ANSWER_ID,
    Q.QUESTION_RAW_TEXT AS RAW,
    Q.QUESTION_REVIEW_COUNT AS REVIEWED,
    Q.QUESTION_CORRECT AS CORRECT,
    Q.QUESTION_INCORRECT AS INCORRECT
FROM (
    SELECT DISTINCT        
    	DECK_NAME, QUESTION_ID, QUESTION_RAW_TEXT,
    	QUESTION_REVIEW_COUNT, QUESTION_CORRECT, QUESTION_INCORRECT, ANSWER_TYPE_ID
    FROM '/home/shay-gaming/Desktop/deck.csv' 
    WHERE ANSWER_TYPE_ID IN (1, 3)
) AS Q
JOIN DECK_IMPORT D ON D.NAME = Q.DECK_NAME 
LEFT JOIN OPEN_ENDED_IMPORT OE ON OE.SRC_QUESTION_ID = Q.QUESTION_ID AND OE.SRC_DECK_NAME = Q.DECK_NAME AND  Q.ANSWER_TYPE_ID = 1
LEFT JOIN ORDERED_SEQUENCE_IMPORT OS ON OS.SRC_QUESTION_ID = Q.QUESTION_ID AND OS.SRC_DECK_NAME = Q.DECK_NAME AND Q.ANSWER_TYPE_ID = 3; 

-- Insert Deck
INSERT INTO DECK (ID, SUBJECT_ID, NAME, TAGS, DESCRIPTION)
SELECT ID, SUBJECT_ID, NAME, TAGS, DESCRIPTION FROM DECK_IMPORT; 

-- Associated deck with subject id
INSERT INTO SUBJECT_DECK (SUBJECT_ID, DECK_ID)
SELECT SUBJECT_ID, ID FROM DECK_IMPORT; 

-- Insert open ended answers
INSERT INTO OPEN_ENDED_ANSWER(ANSWER_ID, KEYWORDS, ANSWER, EXPLANATION)
SELECT ANSWER_ID, KEYWORDS, ANSWER, EXPLANATION FROM OPEN_ENDED_IMPORT; 

-- Insert ordered sequence answers
INSERT INTO ORDERED_SEQUENCE_ANSWER(ANSWER_ID, SEQUENCE, EXPLANATION)
SELECT ANSWER_ID, SEQUENCE, EXPLANATION FROM ORDERED_SEQUENCE_IMPORT; 

-- Insert questions
INSERT INTO QUESTION (ID, DECK_ID, ANSWER_TYPE_ID, ANSWER_ID, REVIEWED, CORRECT, INCORRECT, RAW)
SELECT ID, DECK_ID, ANSWER_TYPE_ID, ANSWER_ID, REVIEWED, CORRECT, INCORRECT, RAW FROM QUESTION_IMPORT;
