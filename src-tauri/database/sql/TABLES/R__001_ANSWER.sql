CREATE SEQUENCE IF NOT EXISTS ANSWER_TYPE_ID_SEQ;
CREATE SEQUENCE IF NOT EXISTS OPEN_ENDED_ANSWER_ID_SEQ;
CREATE SEQUENCE IF NOT EXISTS MULTIPLE_CHOICE_ANSWER_ID_SEQ;
CREATE SEQUENCE IF NOT EXISTS ORDERED_SEQUENCE_ANSWER_ID_SEQ;
CREATE SEQUENCE IF NOT EXISTS MATCHING_ANSWER_ID_SEQ;


CREATE TABLE IF NOT EXISTS ANSWER_TYPE (
    ID          INTEGER     PRIMARY KEY DEFAULT NEXTVAL('ANSWER_TYPE_ID_SEQ'),
    NAME        VARCHAR     NOT NULL,
    CREATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS OPEN_ENDED_ANSWER (
    ANSWER_ID     INTEGER     PRIMARY KEY DEFAULT NEXTVAL('OPEN_ENDED_ANSWER_ID_SEQ'),
    KEYWORDS      VARCHAR[],
    ANSWER        TEXT,
    EXPLANATION   TEXT,
    CREATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS MULTIPLE_CHOICE_ANSWER (
    ANSWER_ID     INTEGER     PRIMARY KEY DEFAULT NEXTVAL('MULTIPLE_CHOICE_ANSWER_ID_SEQ'),
    IS_CORRECT    BOOLEAN     NOT NULL,
    ANSWER        TEXT,
    EXPLANATION   TEXT,
    CREATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS ORDERED_SEQUENCE_ANSWER (
    ANSWER_ID     INTEGER     PRIMARY KEY DEFAULT NEXTVAL('ORDERED_SEQUENCE_ANSWER_ID_SEQ'),
    SEQUENCE      VARCHAR[],
    EXPLANATION   TEXT,
    CREATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS MATCHING_ANSWER (
    ANSWER_ID     INTEGER     PRIMARY KEY DEFAULT NEXTVAL('MATCHING_ANSWER_ID_SEQ'),
    MATCHES       JSON,
    EXPLANATION   TEXT,
    CREATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
