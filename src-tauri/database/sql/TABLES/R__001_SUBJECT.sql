CREATE SEQUENCE IF NOT EXISTS SUBJECT_ID_SEQ;
CREATE SEQUENCE IF NOT EXISTS SUBJECT_DECK_ID_SEQ;


CREATE TABLE IF NOT EXISTS SUBJECT (
    ID          INTEGER     PRIMARY KEY DEFAULT NEXTVAL('SUBJECT_ID_SEQ'),
    NAME        VARCHAR     NOT NULL,
    DESCRIPTION VARCHAR,
    CREATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS SUBJECT_DECK (
    ID          INTEGER     PRIMARY KEY DEFAULT NEXTVAL('SUBJECT_DECK_ID_SEQ'),
    SUBJECT_ID  INTEGER     NOT NULL REFERENCES SUBJECT(ID),
    DECK_ID     INTEGER     NOT NULL,
    CREATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
