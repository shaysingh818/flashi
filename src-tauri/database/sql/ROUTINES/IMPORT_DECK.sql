CREATE OR REPLACE TABLE DECK_IMPORT AS
SELECT
	nextval('DECK_ID_SEQ') AS ID,
	SUBJECT_ID,
	NAME,
	TAGS,
	DESCRIPTION
FROM  (
	SELECT DISTINCT
		{subject_id} AS SUBJECT_ID,
		DECK_NAME AS NAME,
		DECK_TAGS AS TAGS,
		DECK_DESCRIPTION AS DESCRIPTION
	FROM '{path}'
) dedup;
	
CREATE OR REPLACE TABLE OPEN_ENDED_IMPORT AS
SELECT
    nextval('OPEN_ENDED_ANSWER_ID_SEQ') AS ANSWER_ID,
    DECK_NAME AS SRC_DECK_NAME,
    QUESTION_ID AS SRC_QUESTION_ID,
    OPEN_ENDED_ANSWER_KEYWORDS AS KEYWORDS,
    OPEN_ENDED_ANSWER AS ANSWER,
    OPEN_ENDED_EXPLANATION AS EXPLANATION
FROM (
    SELECT DISTINCT
        DECK_NAME, QUESTION_ID, OPEN_ENDED_ANSWER_KEYWORDS, OPEN_ENDED_ANSWER, OPEN_ENDED_EXPLANATION
    FROM '{path}'
    WHERE ANSWER_TYPE_ID = 1
) dedup;

CREATE OR REPLACE TABLE ORDERED_SEQUENCE_IMPORT AS
SELECT
    nextval('ORDERED_SEQUENCE_ANSWER_ID_SEQ') AS ANSWER_ID,
    DECK_NAME AS SRC_DECK_NAME,
    QUESTION_ID AS SRC_QUESTION_ID,
    ORDERED_SEQUENCE_VALUE AS SEQUENCE,
    ORDERED_SEQUENCE_EXPLANATION AS EXPLANATION
FROM (
    SELECT DISTINCT
        DECK_NAME, QUESTION_ID, ORDERED_SEQUENCE_VALUE, ORDERED_SEQUENCE_EXPLANATION
    FROM '{path}'
    WHERE ANSWER_TYPE_ID = 3
) dedup;

CREATE OR REPLACE TABLE MULTIPLE_CHOICE_IMPORT AS
SELECT
    nextval('MULTIPLE_CHOICE_ID_SEQ') AS ANSWER_ID,
    DECK_NAME AS SRC_DECK_NAME,
    QUESTION_ID AS SRC_QUESTION_ID
FROM (
    SELECT DISTINCT
        DECK_NAME, QUESTION_ID
    FROM '{path}'
    WHERE ANSWER_TYPE_ID = 2
) dedup;

CREATE OR REPLACE TABLE MULTIPLE_CHOICE_ANSWER_IMPORT AS
SELECT
    nextval('MULTIPLE_CHOICE_ANSWER_ID_SEQ') AS ID,
    MC.ANSWER_ID,
    O.IS_CORRECT,
    O.ANSWER
FROM (
    SELECT DISTINCT
        DECK_NAME, QUESTION_ID,
        MULTIPLE_CHOICE_IS_CORRECT::BOOLEAN AS IS_CORRECT,
        MULTIPLE_CHOICE_ANSWER AS ANSWER
    FROM '{path}'
    WHERE ANSWER_TYPE_ID = 2
) AS O
JOIN MULTIPLE_CHOICE_IMPORT MC ON MC.SRC_QUESTION_ID = O.QUESTION_ID AND MC.SRC_DECK_NAME = O.DECK_NAME;

CREATE OR REPLACE TABLE IMAGE_ARTIFACT_IMPORT AS
SELECT
    nextval('IMAGE_ARTIFACT_ID_SEQ') AS ID,
    IMAGE_PATH
FROM (
    SELECT DISTINCT
        QUESTION_IMAGE_ARTIFACT AS IMAGE_PATH
    FROM '{path}'
    WHERE QUESTION_IMAGE_ARTIFACT IS NOT NULL
) dedup;

CREATE OR REPLACE TABLE QUESTION_IMPORT AS
SELECT
    nextval('QUESTION_ID_SEQ') AS ID,
    Q.DECK_NAME AS SRC_DECK_NAME,
    Q.QUESTION_ID AS SRC_QUESTION_ID,
    D.ID AS DECK_ID,
    Q.ANSWER_TYPE_ID,
    COALESCE(OE.ANSWER_ID, MC.ANSWER_ID, OS.ANSWER_ID) AS ANSWER_ID,
    Q.QUESTION_RAW_TEXT AS RAW,
    Q.QUESTION_REVIEW_COUNT AS REVIEWED,
    Q.QUESTION_CORRECT AS CORRECT,
    Q.QUESTION_INCORRECT AS INCORRECT
FROM (
    SELECT DISTINCT        
    	DECK_NAME, QUESTION_ID, QUESTION_RAW_TEXT,
    	QUESTION_REVIEW_COUNT, QUESTION_CORRECT, QUESTION_INCORRECT, ANSWER_TYPE_ID
    FROM '{path}' 
    WHERE ANSWER_TYPE_ID IN (1, 2, 3)
) AS Q
JOIN DECK_IMPORT D ON D.NAME = Q.DECK_NAME 
LEFT JOIN OPEN_ENDED_IMPORT OE ON OE.SRC_QUESTION_ID = Q.QUESTION_ID AND OE.SRC_DECK_NAME = Q.DECK_NAME AND  Q.ANSWER_TYPE_ID = 1
LEFT JOIN MULTIPLE_CHOICE_IMPORT MC ON MC.SRC_QUESTION_ID = Q.QUESTION_ID AND MC.SRC_DECK_NAME = Q.DECK_NAME AND Q.ANSWER_TYPE_ID = 2
LEFT JOIN ORDERED_SEQUENCE_IMPORT OS ON OS.SRC_QUESTION_ID = Q.QUESTION_ID AND OS.SRC_DECK_NAME = Q.DECK_NAME AND Q.ANSWER_TYPE_ID = 3; 

INSERT INTO DECK (ID, SUBJECT_ID, NAME, TAGS, DESCRIPTION)
SELECT ID, SUBJECT_ID, NAME, TAGS, DESCRIPTION FROM DECK_IMPORT; 

INSERT INTO SUBJECT_DECK (SUBJECT_ID, DECK_ID)
SELECT SUBJECT_ID, ID FROM DECK_IMPORT; 

INSERT INTO OPEN_ENDED_ANSWER(ANSWER_ID, KEYWORDS, ANSWER, EXPLANATION)
SELECT ANSWER_ID, KEYWORDS, ANSWER, COALESCE(EXPLANATION, '') AS EXPLANATION FROM OPEN_ENDED_IMPORT; 

INSERT INTO MULTIPLE_CHOICE(ANSWER_ID)
SELECT ANSWER_ID FROM MULTIPLE_CHOICE_IMPORT;

INSERT INTO MULTIPLE_CHOICE_ANSWER(ID, ANSWER_ID, IS_CORRECT, ANSWER, EXPLANATION)
SELECT ID, ANSWER_ID, IS_CORRECT, ANSWER, '' AS EXPLANATION FROM MULTIPLE_CHOICE_ANSWER_IMPORT;

INSERT INTO ORDERED_SEQUENCE_ANSWER(ANSWER_ID, SEQUENCE, EXPLANATION)
SELECT ANSWER_ID, SEQUENCE, COALESCE(EXPLANATION, '') AS EXPLANATION FROM ORDERED_SEQUENCE_IMPORT; 

INSERT INTO QUESTION (ID, DECK_ID, ANSWER_TYPE_ID, ANSWER_ID, REVIEWED, CORRECT, INCORRECT, RAW)
SELECT ID, DECK_ID, ANSWER_TYPE_ID, ANSWER_ID, REVIEWED, CORRECT, INCORRECT, RAW FROM QUESTION_IMPORT;

INSERT INTO IMAGE_ARTIFACT(ID, IMAGE_PATH)
SELECT ID, IMAGE_PATH FROM IMAGE_ARTIFACT_IMPORT;

INSERT INTO QUESTION_IMAGE(QUESTION_ID, IMAGE_ID)
SELECT DISTINCT Q.ID, IA.ID
FROM '{path}' AS SRC
JOIN QUESTION_IMPORT Q ON Q.SRC_QUESTION_ID = SRC.QUESTION_ID AND Q.SRC_DECK_NAME = SRC.DECK_NAME
JOIN IMAGE_ARTIFACT_IMPORT IA ON IA.IMAGE_PATH = SRC.QUESTION_IMAGE_ARTIFACT;
